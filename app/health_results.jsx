import React, { useState } from 'react'
import { StyleSheet, Text, View, TextInput, TouchableOpacity, ScrollView, SafeAreaView } from 'react-native'
import { useLocalSearchParams, useRouter } from 'expo-router'
import { Ionicons } from '@expo/vector-icons'
import {
  useFonts,
  Montserrat_400Regular,
  Montserrat_600SemiBold,
  Montserrat_700Bold,
} from '@expo-google-fonts/montserrat'

export default function HealthResult() {
  const router = useRouter()
  const params = useLocalSearchParams()

  const [fieldNotes, setFieldNotes] = useState('')

  const [fontsLoaded] = useFonts({
    Montserrat_400Regular,
    Montserrat_600SemiBold,
    Montserrat_700Bold,
  })
  if (!fontsLoaded) return null

  // Placeholder state for AI health result
  const readableLocationParts = [
    params.purok,
    params.street,
    params.barangay,
    params.city,
    params.province,
    params.region,
  ].filter(Boolean)

  const readableLocation = readableLocationParts.join(', ')

  const healthResult = '' // empty for now
  const healthDescription = '' // empty for now

  const formattedDate = params.timestamp
    ? new Date(params.timestamp).toLocaleDateString()
    : 'Unknown Date'

  return (
    <View style={styles.container}>
      <ScrollView contentContainerStyle={styles.content}>

        {/* Health Status Card */}
        <View style={styles.card}>
          <View style={styles.statusRow}>
            <View style={styles.iconCircle}>
              <Ionicons name="heart-circle-outline" size={26} color="#6DAA1A" />
            </View>
            <View style={{ flex: 1 }}>
              <Text style={styles.healthTitle}>{healthResult || 'Health Status'}</Text>
              <Text style={styles.healthDescription}>
                {healthDescription || 'Classification will appear here once AI model is implemented.'}
              </Text>
              <Text style={styles.healthDisclaimer}>
                Classification generated by trained AI model. Intended for preliminary environmental assessment only.
              </Text>
            </View>
          </View>
        </View>

        {/* Field Notes */}
        <View style={styles.card}>
          <Text style={styles.label}>Field Notes (Optional)</Text>
          <TextInput
            style={styles.textArea}
            multiline
            placeholder="Describe any additional observations: debris, oil spills, unusual conditions, wildlife presence, weather conditions..."
            placeholderTextColor="#9CA3AF"
            value={fieldNotes}
            onChangeText={setFieldNotes}
            maxLength={500}
          />
          <Text style={styles.charCount}>{fieldNotes.length}/500 characters</Text>
        </View>

        {/* Report Summary */}
        <View style={styles.card}>
          <Text style={styles.label}>Report Summary</Text>
          <View style={styles.summaryRow}>
            <Text style={styles.summaryLabel}>Species:</Text>
            <Text style={styles.summaryValue}>{params.speciesName || ''}</Text>
          </View>
          <View style={styles.summaryRow}>
            <Text style={styles.summaryLabel}>Condition:</Text>
            <Text style={[styles.summaryValue, { color: healthResult ? '#2DA031' : '#6E756A' }]}>{healthResult || ''}</Text>
          </View>
          <View style={styles.summaryRow}>
            <Text style={styles.summaryLabel}>Location:</Text>
            <Text style={styles.summaryValue}>{readableLocation || params.formattedAddress || 'N/A'}</Text>
          </View>
          <View style={styles.summaryRow}>
            <Text style={styles.summaryLabel}>GPS:</Text>
            <Text style={styles.summaryValue}>
              {params.latitude || '0.000000'}, {params.longitude || '0.000000'}
            </Text>
          </View>
          <View style={styles.summaryRow}>
            <Text style={styles.summaryLabel}>Date:</Text>
            <Text style={styles.summaryValue}>{formattedDate}</Text>
          </View>
        </View>

      </ScrollView>

      {/* Floating Header Overlay */}
      <SafeAreaView style={styles.headerOverlay} pointerEvents="box-none">
        <View style={styles.topOverlay}>
          <TouchableOpacity
            style={styles.backButton}
            onPress={() => router.back()}
            activeOpacity={0.8}
          >
            <Ionicons name="chevron-back" size={24} color="#fff" />
          </TouchableOpacity>
        </View>
      </SafeAreaView>

      {/* Fixed Action Button Dock */}
      <View style={styles.buttonDock}>
        <TouchableOpacity style={styles.primaryButton} onPress={() => {}}>
          <Ionicons name="checkmark-circle-outline" size={22} color="#FFFFFF" />
          <Text style={styles.primaryButtonText}>Submit Report</Text>
        </TouchableOpacity>
      </View>
    </View>
  )
}

